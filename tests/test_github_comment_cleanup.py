def select(selection, repo: Path, state: dict, **overrides):
    args = {"include": [], "exclude": [], "max_files": 100, "max_bytes": 1_000_000} | overrides
    return selection.select_files(repo, selection.tree_blobs(repo), state, **args)


def test_first_run_queues_commented_files_and_clears_comment_free_ones(selection, repo):
    result = select(selection, repo, {"files": {}})

    assert set(result.queue) == COMMENTED
    assert set(result.auto_cleared) == COMMENT_FREE
    blobs = selection.tree_blobs(repo)
    assert all(result.queue[p] == blobs[p] for p in result.queue)


def test_recorded_fingerprints_are_not_read_again(selection, repo):
    state = {"files": {}}
    first = select(selection, repo, state)
    selection.record(state, {p: [fp] for p, fp in {**first.queue, **first.auto_cleared}.items()}, "2026-10-28")

    assert not select(selection, repo, state).queue


def test_a_changed_file_is_queued_ahead_of_unseen_files(selection, repo):
    state = {"files": {}}
    selection.record(state, {"src/msg.py": [selection.tree_blobs(repo)["src/msg.py"]]}, "2026-10-28")
    commit(repo, {"src/msg.py": FILES["src/msg.py"] + "# new comment\nx = 1\n"})

    result = select(selection, repo, state, max_files=1)

    assert list(result.queue) == ["src/msg.py"]
    assert result.deferred == 2


def test_include_exclude_and_byte_cap(selection, repo):
    assert set(select(selection, repo, {"files": {}}, include=["src/*"]).queue) == {"src/app.ts", "src/msg.py"}
    assert set(select(selection, repo, {"files": {}}, exclude=["*.md"]).queue) == {"src/app.ts", "src/msg.py"}
    capped = select(selection, repo, {"files": {}}, max_bytes=1)
    assert len(capped.queue) == 1 and capped.deferred == 2


def test_a_cleaned_file_stays_clean_whether_the_pull_request_is_merged_or_closed(selection, repo):
    state = {"files": {}}
    queued = select(selection, repo, state).queue
    cleaned = FILES["src/msg.py"].replace("    # Get the content text from the message\n", "")
    cleaned_blob = blob(repo, cleaned)

    selection.record(state, selection.examined_fingerprints(queued, {"src/msg.py": cleaned_blob}), "2026-10-28")

    assert state["files"]["src/msg.py"]["fp"] == [queued["src/msg.py"], cleaned_blob]
    assert state["files"]["README.md"]["fp"] == [queued["README.md"]]
    assert not select(selection, repo, state).queue, "closed: the originals are recorded"
    commit(repo, {"src/msg.py": cleaned}, "merge cleanup")
    assert not select(selection, repo, state).queue, "merged: the cleaned fingerprint is recorded"


def test_prune_drops_deleted_paths(selection, repo):
    state = {"files": {}}
    selection.record(state, {"gone.py": ["abc"], "src/msg.py": ["def"]}, "2026-10-28")

    selection.prune(state, selection.tree_blobs(repo))

    assert list(state["files"]) == ["src/msg.py"]


