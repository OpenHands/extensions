"""Pick the files a scheduled run hands to the agent, and fold finished runs back into state.

A file's fingerprint is its git blob SHA, the same value `git ls-tree` and the GitHub API
report. State maps each examined path to the fingerprints it was declared clean at:

    {"files": {"src/app.py": {"at": "2026-10-28", "fp": ["<sha>", ...]}}, ...}

A file is queued only when its current fingerprint is not among them.
"""

from __future__ import annotations

import fnmatch
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

# A catalog bundle packs comment_syntax.py beside this file; the plugin reaches it through skills/.
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "skills" / "comment-cleanup" / "scripts"))
from comment_syntax import is_default_excluded, kind_for, scan, syntax_for  # noqa: E402

MAX_FILE_BYTES = 200_000
GENERATED_RE = re.compile(r"@generated|do not edit|auto-?generated|code generated by", re.IGNORECASE)


@dataclass
class Selection:
    queue: dict[str, str] = field(default_factory=dict)
    auto_cleared: dict[str, str] = field(default_factory=dict)
    deferred: int = 0


def tree_blobs(checkout: Path) -> dict[str, str]:
    """Map every regular file at HEAD of `checkout` to its blob SHA."""
    tree = subprocess.run(
        ["git", "-c", "core.quotePath=false", "ls-tree", "-r", "-z", "HEAD"],
        cwd=checkout, capture_output=True, text=True, check=True,
    ).stdout
    blobs = {}
    for entry in filter(None, tree.split("\0")):
        meta, path = entry.split("\t", 1)
        mode, kind, sha = meta.split()
        if kind == "blob" and mode != "120000":
            blobs[path] = sha
    return blobs


def known_fingerprints(state: dict) -> set[str]:
    return {fp for entry in state["files"].values() for fp in entry["fp"]}


def select_files(
    root: Path,
    blobs: dict[str, str],
    state: dict,
    include: list[str],
    exclude: list[str],
    max_files: int,
    max_bytes: int,
) -> Selection:
    """Return the queue for this run from a checkout at `root` whose tree is `blobs` (path -> fingerprint).

    Comment-free code files are returned in `auto_cleared` so they are recorded without the
    agent reading them. Files that changed since an earlier examination are queued before
    files never seen, because they are the likeliest to carry fresh agent-written comments.
    """
    known = known_fingerprints(state)
    selection = Selection()
    candidates: list[tuple[int, str, int]] = []
    for path, fp in sorted(blobs.items()):
        kind = kind_for(path)
        if kind is None or fp in known:
            continue
        if include and not any(fnmatch.fnmatch(path, g) for g in include):
            continue
        if any(fnmatch.fnmatch(path, g) for g in exclude) or is_default_excluded(path):
            continue
        full = root / path
        size = full.stat().st_size
        if size == 0 or size > MAX_FILE_BYTES:
            continue
        text = full.read_text(errors="replace")
        if GENERATED_RE.search(text[:2000]):
            continue
        if kind == "code" and scan(text, syntax_for(path))[1] == 0:
            selection.auto_cleared[path] = fp
            continue
        candidates.append((0 if path in state["files"] else 1, path, size))

    candidates.sort()
    total = 0
    for _, path, size in candidates:
        if len(selection.queue) >= max_files or (selection.queue and total + size > max_bytes):
            selection.deferred += 1
            continue
        selection.queue[path] = blobs[path]
        total += size
    return selection


def examined_fingerprints(queued: dict[str, str], pr_blobs: dict[str, str]) -> dict[str, list[str]]:
    """Fingerprints to record for each queued file once its conversation has finished.

    `pr_blobs` holds the fingerprints of files the cleanup PR changed (empty when the agent
    found nothing to change). Both the original and the cleaned fingerprint are kept, so the
    file stays clean whether the PR is merged or a human closes it.
    """
    result = {}
    for path, original in queued.items():
        cleaned = pr_blobs.get(path)
        result[path] = [original] if cleaned in (None, original) else [original, cleaned]
    return result


def record(state: dict, fingerprints: dict[str, list[str]], date: str) -> None:
    for path, fps in fingerprints.items():
        state["files"][path] = {"at": date, "fp": fps}


def prune(state: dict, blobs: dict[str, str]) -> None:
    state["files"] = {p: e for p, e in state["files"].items() if p in blobs}
