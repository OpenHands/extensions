"""Pure triage contracts and optimistic, fail-closed GitHub publication."""

import argparse
import hashlib
import json
import re
from pathlib import Path
from urllib.parse import quote, unquote

from github_client import GitHubRepository

START = "<!-- openhands-ai-triage:start -->"
END = "<!-- openhands-ai-triage:end -->"
VERSION = 3
DISCLOSURE = "_Generated by an AI agent (OpenHands) on behalf of the automation owner._"


def split_body(body):
    body = body or ""
    if START not in body and END not in body:
        return body, "", ""
    if body.count(START) != 1 or body.count(END) != 1:
        raise ValueError("Ambiguous managed markers; human repair required")
    start, end = body.index(START), body.index(END)
    if end < start:
        raise ValueError("Reversed managed markers")
    return body[:start], body[start : end + len(END)], body[end + len(END) :]


def author_body(body):
    before, _, after = split_body(body)
    return (before + after).rstrip()


def owned_comment(comment, login):
    return (
        bool(login)
        and (comment.get("user") or {}).get("login") == login
        and bool(
            re.search(r"<!-- triage-source:[a-f0-9]{64} -->", comment.get("body") or "")
        )
    )


def readiness_comment(comment):
    return (comment.get("user") or {}).get(
        "login"
    ) == "github-actions[bot]" and "<!-- issue-readiness-check -->" in (
        comment.get("body") or ""
    )


def readiness_transitions(repo, number, login):
    return [
        (e.get("id"), e.get("event"), e.get("created_at"))
        for e in repo.gh_pages(f"/issues/{number}/timeline")
        if e.get("event") in {"labeled", "unlabeled"}
        and (e.get("label") or {}).get("name") == "ready-for-dev"
        and (e.get("actor") or {}).get("login") != login
        and (e.get("actor") or {}).get("login") != "github-actions[bot]"
    ]


def fingerprint(issue, comments, login, transitions=(), policy=None):
    return hashlib.sha256(
        json.dumps(
            [
                VERSION,
                issue["title"],
                author_body(issue.get("body")),
                list(transitions),
                policy,
                [
                    (
                        c["id"],
                        c.get("updated_at"),
                        c.get("body"),
                        (c.get("user") or {}).get("login"),
                    )
                    for c in comments
                    if not owned_comment(c, login) and not readiness_comment(c)
                ],
            ],
            sort_keys=True,
        ).encode()
    ).hexdigest()


def parse_recommendation(value):
    if isinstance(value, str):
        value = json.loads(value)
    required = {"decision", "priority", "scope", "non_goals", "criteria", "questions"}
    if not isinstance(value, dict) or set(value) != required:
        raise ValueError("Recommendation must contain exactly the documented fields")
    if value["decision"] not in ("ready", "decision_needed") or value[
        "priority"
    ] not in ("high", "medium", "low"):
        raise ValueError("Invalid decision or priority")
    for key in ("scope", "non_goals"):
        if not isinstance(value[key], str) or not value[key].strip():
            raise ValueError(f"Missing {key}")
    for key in ("criteria", "questions"):
        if not isinstance(value[key], list) or any(
            not isinstance(s, str) or not s.strip() for s in value[key]
        ):
            raise ValueError(f"Invalid {key}")
    if value["decision"] == "ready":
        if not value["criteria"] or value["questions"]:
            raise ValueError("Ready requires criteria and no open questions")
    elif not value["questions"] or value["criteria"]:
        raise ValueError(
            "Decision needed requires questions and no provisional criteria"
        )
    if "<!--" in json.dumps(value) or len(json.dumps(value)) > 20000:
        raise ValueError("Embedded markers or oversized recommendation")
    return value


def render(body, recommendation, digest):
    r = parse_recommendation(recommendation)
    before, old, after = split_body(body)
    marker = f"<!-- triage-source:{digest} -->"
    if not re.fullmatch(r"[a-f0-9]{64}", digest):
        raise ValueError("Invalid input digest")
    if r["decision"] == "decision_needed":
        return before + after, f"{DISCLOSURE}\n\n### Decision needed\n" + "\n".join(
            f"- {q}" for q in r["questions"]
        ) + f"\n\n{marker}"
    section = (
        f"{START}\n## OpenHands AI triage\n{DISCLOSURE}\n\n"
        f"### Scope\n{r['scope']}\n\n### Non-goals\n{r['non_goals']}\n\n"
        "### Acceptance Criteria\n"
        + "\n".join(f"- [ ] {c}" for c in r["criteria"])
        + f"\n\n{marker}\n{END}"
    )
    return before + ("" if old else "\n\n") + section + after, None


def writer_policy_allows(repo, login):
    """Only deployment-audited writer-only policies are supported, never repo code."""
    policy = repo.config.get("triage_readiness_policies", {}).get(repo.repository, {})
    if policy.get("mode") != "authorized-writers" or not policy.get("files"):
        return False
    for path, sha in policy["files"].items():
        if not re.fullmatch(r"[a-f0-9]{40}", sha):
            return False
        current = repo.gh("GET", f"/contents/{quote(path, safe='/')}")
        if current.get("sha") != sha:
            return False
    permission = repo.gh("GET", f"/collaborators/{quote(login, safe='')}/permission")
    return permission.get("permission") in {"write", "maintain", "admin"}


def publish(repo, number, expected, recommendation):
    r = parse_recommendation(recommendation)
    login = repo.api("GET", "/user")["login"]
    path = f"/issues/{number}"
    initial = repo.gh("GET", path)
    comments = repo.gh_pages(path + "/comments")
    if initial.get("state") != "open" or "pull_request" in initial:
        raise ValueError("Issue no longer eligible")
    if (
        fingerprint(
            initial,
            comments,
            login,
            readiness_transitions(repo, number, login),
            repo.config.get("triage_readiness_policies"),
        )
        != expected
    ):
        raise ValueError("Human inputs changed; recompute recommendation")
    body, comment = render(initial.get("body"), r, expected)
    receipt = f"<!-- triage-complete:{expected} -->"
    body = body.replace(receipt, "")
    labels = {label["name"] for label in initial.get("labels", [])}
    writes = 0

    def guarded(method, target, data=None):
        nonlocal initial, writes
        current = repo.gh("GET", path)
        fresh_comments = repo.gh_pages(path + "/comments")
        if (
            current.get("state") != "open"
            or {l["name"] for l in current.get("labels", [])} != labels
            or current.get("body") != initial.get("body")
            or fingerprint(
                current,
                fresh_comments,
                login,
                readiness_transitions(repo, number, login),
                repo.config.get("triage_readiness_policies"),
            )
            != expected
        ):
            raise ValueError("Inputs changed before write; recompute recommendation")
        result = repo.gh(method, target, data)
        writes += 1
        if target == path and method == "PATCH":
            initial = {**initial, "body": data["body"]}
        if target == path + "/labels" and method == "POST":
            labels.update(data["labels"])
        elif target.startswith(path + "/labels/") and method == "DELETE":
            labels.discard(unquote(target.rsplit("/", 1)[1]))
        return result

    # Revoke readiness before changing its supporting criteria.
    labels = {label["name"] for label in initial.get("labels", [])}
    allowed = r["decision"] == "ready" and writer_policy_allows(repo, login)
    if "ready-for-dev" in labels and r["decision"] == "decision_needed":
        guarded("DELETE", path + "/labels/ready-for-dev")
    completed_body = (
        body.replace(END, receipt + "\n" + END) if r["decision"] == "ready" else body
    )
    if body != (initial.get("body") or "") and completed_body != (
        initial.get("body") or ""
    ):
        guarded("PATCH", path, {"body": body})
    own = [c for c in comments if owned_comment(c, login)]
    if comment and not any(
        c.get("body") in (comment, comment + "\n" + receipt) for c in own
    ):
        if own:
            guarded("PATCH", f"/issues/comments/{own[0]['id']}", {"body": comment})
            own = own[1:]
        else:
            guarded("POST", path + "/comments", {"body": comment})
    else:
        own = [
            c
            for c in own
            if c.get("body")
            not in (comment, (comment + "\n" + receipt) if comment else None)
        ]
    for c in own:
        guarded("DELETE", f"/issues/comments/{c['id']}")
    priority = "priority:" + r["priority"]
    for other in sorted(
        labels
        & {"priority:normal", "priority:high", "priority:medium", "priority:low"}
        - {priority}
    ):
        guarded("DELETE", path + "/labels/" + quote(other, safe=""))
    if priority not in labels:
        guarded("POST", path + "/labels", {"labels": [priority]})
    if allowed and "ready-for-dev" not in labels and writer_policy_allows(repo, login):
        guarded("POST", path + "/labels", {"labels": ["ready-for-dev"]})
    if r["decision"] == "ready":
        if completed_body != (initial.get("body") or ""):
            guarded("PATCH", path, {"body": completed_body})
    elif comment:
        current_comments = repo.gh_pages(path + "/comments")
        target = next(
            c
            for c in current_comments
            if owned_comment(c, login) and expected in c.get("body", "")
        )
        completed_comment = comment + "\n" + receipt
        if target.get("body") != completed_comment:
            guarded(
                "PATCH", f"/issues/comments/{target['id']}", {"body": completed_comment}
            )
    return {"writes": writes, "readiness_policy_allowed": allowed}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", required=True)
    parser.add_argument("--repository", required=True)
    parser.add_argument("--number", required=True, type=int)
    parser.add_argument("--expected", required=True)
    parser.add_argument("--recommendation", required=True)
    parser.add_argument("--github-token-secret", required=True)
    args = parser.parse_args()
    config = json.loads(Path(args.config).read_text())
    if args.repository not in (config.get("repos") or [config.get("repository")]):
        raise ValueError("Repository not allowed by deployment")
    repo = GitHubRepository(
        args.config,
        repository=args.repository,
        github_token_secret=args.github_token_secret,
    )
    print(
        json.dumps(
            publish(
                repo, args.number, args.expected, Path(args.recommendation).read_text()
            )
        )
    )


if __name__ == "__main__":
    main()
