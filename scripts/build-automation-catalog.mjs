import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const catalogDir = path.join(root, "automations", "catalog");
const outputPath = path.join(root, "automations", "catalog-index.js");

const directories = (await readdir(catalogDir, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort((left, right) => left.localeCompare(right));

const automations = await Promise.all(
  directories.map(async (directory) => ({
    directory,
    entry: JSON.parse(
      await readFile(path.join(catalogDir, directory, "manifest.json"), "utf8"),
    ),
  })),
);

automations.sort((left, right) => {
  const rank = (right.entry.popularityRank ?? -1) - (left.entry.popularityRank ?? -1);
  return rank || left.entry.id.localeCompare(right.entry.id);
});

const indexedAutomations = automations.map((automation, index) => ({
  ...automation,
  importName: `entry${index}`,
}));

const imports = indexedAutomations
  .map(
    ({ directory, importName }) =>
      `import ${importName} from "./catalog/${directory}/manifest.json" with { type: "json" };`,
  )
  .join("\n");
const entries = indexedAutomations.map(({ importName }) => `  ${importName},`).join("\n");

const header = `// This file is auto-generated by scripts/build-automation-catalog.mjs.
// Do not edit it manually. To update it after changing automations/catalog/*/manifest.json,
// run: npm run build:automations

`;
const body = `${header}${imports}

export const AUTOMATION_CATALOG_ENTRIES = [
${entries}
];
`;
await writeFile(outputPath, body);
